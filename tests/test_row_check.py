def test_designation_is_not_a_number() -> None:
    """«ЯМЗ-236М2» — обозначение: «236» не ищется в строках таблицы."""
    q = "При какой частоте вращения при номинальной мощности?"
    assert row_ok("У ЯМЗ-236М2 частота вращения при номинальной мощности — 2100 об/мин [R1].", q, [SPECS])
    assert not row_ok("У ЯМЗ-236М2 частота вращения коленчатого вала — 667 об/мин [R1].", q, [SPECS])  # чужая строка


def test_value_without_name_in_column_table_is_not_judged() -> None:
    """Таблица по моделям: значение «883» на своей строке без названия — строку не узнать, не снимаем."""
    assert row_ok("ЯМЗ-238М2: 883 Н·м [R1].", "Какой максимальный крутящий момент?", [SPECS])


def test_prose_line_ending_with_number_is_text() -> None:
    """«…усилием 39,2» / «должен быть от 4 до 8 мм.» — обычный текст, а не строка таблицы."""
    q = "На сколько должен прогибаться ремень компрессора?"
    assert row_ok("Ремень — 4–8 мм, нагрузка 39,2 Н [R2].", q, [BELT])
    assert row_ok("Болты компрессора — от 28 до 36 Н·м [R2].", q, [BELT])  # в тексте — не проверяется, как и было


def test_whole_range_of_a_row_with_common_words_passes() -> None:
    """Все слова строки есть и в соседних строках: диапазон целиком и два слова совпадения — строка своя."""
    q = "На гильзе выбита буква Б. Какой у неё внутренний диаметр?"
