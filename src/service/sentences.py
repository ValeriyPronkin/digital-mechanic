"""Граница фразы — одна для всех правил кода, которые режут ответ по фразам (guard, отказ, противоречия, озвучка).

Фраза кончается точкой, «!» или «?» перед заглавной буквой (или кавычкой, скобкой с ней). После сокращений
(«рис.», «стр.», «св.», «п.», «поз.», «т. е.») — не кончается. Иначе код резал «св. 130,02 до 130,04» и
«по рис. 6 [R1]» посередине: одна половина снималась, другая оставалась обрывком без ссылки (#90, приёмщик 27.11)."""

from __future__ import annotations

import re

_ABBR = ("рис", "стр", "табл", "п", "пп", "поз", "см", "т. е", "т.е", "св", "ср", "гл", "разд", "прил")
SENTENCE_END = "".join(rf"(?<!\b{re.escape(a)}\.)" for a in _ABBR) + r"(?<=[.!?])\s+(?=[«\"(]?[А-ЯЁA-Z])"
SPLIT = re.compile(SENTENCE_END)
